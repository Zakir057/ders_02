--TASK 1

SELECT JOB_ID, COUNT(*) AS ISCI_SAYI, FLOOR(AVG(SALARY)) AS ORTA_MAAS
FROM HR.EMPLOYEES
GROUP BY JOB_ID
ORDER BY ISCI_SAYI DESC;

--TASK 2

SELECT DEPARTMENT_ID, MAX(SALARY) AS MAX_MAAS, MIN(SALARY) AS MIN_MAAS
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
ORDER BY DEPARTMENT_ID ASC;

--TASK 3

SELECT A.DEPARTMENT_NAME, Z.CITY
FROM HR.DEPARTMENTS A
JOIN HR.LOCATIONS Z
ON A.LOCATION_ID = Z.LOCATION_ID;

--TASK 4

SELECT JOB_ID, SUM(SALARY) AS MAAS_CEMI
FROM HR.EMPLOYEES
GROUP BY JOB_ID
HAVING SUM(SALARY)>50000
ORDER BY MAAS_CEMI DESC;

--TASK 5

SELECT MANAGER_ID, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
WHERE COMMISSION_PCT IS NOT NULL
GROUP BY MANAGER_ID
HAVING COUNT(*) >5;

--TASK 6

SELECT S.CITY, COUNT(F.DEPARTMENT_ID) AS SOBE_SAYI
FROM HR.LOCATIONS S
LEFT JOIN HR.DEPARTMENTS F
ON S.LOCATION_ID = F.LOCATION_ID
GROUP BY S.CITY
ORDER BY SOBE_SAYI DESC;

--TASK 7

SELECT A.FIRST_NAME, A.LAST_NAME, Z.DEPARTMENT_NAME
FROM HR.EMPLOYEES A
FULL OUTER JOIN HR.DEPARTMENTS Z 
ON A.DEPARTMENT_ID = Z.DEPARTMENT_ID
WHERE Z.DEPARTMENT_ID IS NULL OR A.EMPLOYEE_ID IS NULL;

--TASK 8 

-- YANLIS KOD
SELECT D.DEPARTMENT_NAME, E.FIRST_NAME, COUNT(*) AS ISCI_SAYI -- 1) FIRST NAME ISLENE BILMEZ CUNKI GROUP BY D.DEPARTMENT_NAME VAR
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D ON DEPARTMENT_ID = D.DEPARTMENT_ID   -- 2)SEHV E.
WHERE COUNT(*) > 3      -- 3) HAVING OLMALIDI CUNKI GROUP BY ILE WHERE ISLENMIR 
GROUP BY D.DEPARTMENT_NAME;

-- DOGRU KOD

SELECT D.DEPARTMENT_NAME, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
HAVING COUNT(*) > 3
GROUP BY D.DEPARTMENT_NAME;

--TASK 9

SELECT A.DEPARTMENT_NAME AS DEPARTMENT_NAME, B.JOB_TITLE AS JOB_TITLE, COUNT(*) AS ISCI_SAYI, CEIL(AVG(C.SALARY)) AS ORTA_MAAS
FROM HR.EMPLOYEES C
 JOIN HR.DEPARTMENTS A 
 ON C.DEPARTMENT_ID = A.DEPARTMENT_ID
       JOIN HR.JOBS B 
       ON C.JOB_ID = B.JOB_ID
GROUP BY A.DEPARTMENT_NAME, B.JOB_TITLE
HAVING COUNT(*) >= 3
ORDER BY A.DEPARTMENT_NAME ASC, COUNT(*) DESC;

--TASK 10

SELECT E.EMPLOYEE_ID AS EMPLOYEE_ID,
       E.FIRST_NAME AS FIRST_NAME,
       E.LAST_NAME AS LAST_NAME,
       COUNT(G.EMPLOYEE_ID) AS KECMIS_VEZIFE_SAYI
FROM HR.EMPLOYEES E
       LEFT JOIN HR.JOB_HISTORY G ON E.EMPLOYEE_ID = G.EMPLOYEE_ID
GROUP BY E.EMPLOYEE_ID, E.FIRST_NAME, E.LAST_NAME
ORDER BY KECMIS_VEZIFE_SAYI DESC, E.EMPLOYEE_ID;